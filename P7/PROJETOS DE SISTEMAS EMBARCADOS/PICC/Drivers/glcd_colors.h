#define GLCD_COLORS_ORANGE 0xFC00
#define GLCD_COLORS_YELLOW 0xFFE0
#define GLCD_COLORS_GREEN  0x07E0
#define GLCD_COLORS_BLUE   0x001F
#define GLCD_COLORS_PURPLE 0x4010
#define GLCD_COLORS_CYAN   0x07FF
#define GLCD_COLORS_PINK   0xF81F
#define GLCD_COLORS_BLACK  0x0000
#define GLCD_COLORS_GREY   0x8410
#define GLCD_COLORS_WHITE  0xFFFF
#define GLCD_COLORS_BROWN  0x8200

